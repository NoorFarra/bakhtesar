function bindArticleTriggers() {
  document.querySelectorAll('[data-open-article]').forEach(el => {
    el.onclick = () => openArticle(+el.dataset.openArticle);
    el.onkeydown = e => {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        openArticle(+el.dataset.openArticle);
      }
    };
  });
}

