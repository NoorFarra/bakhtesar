function setHero(target, requestedDirection, resetAutoplay = true) {
  const slides = document.getElementById('immersiveSlides');
  const dots = document.getElementById('heroDots');
  const count = slides?.children.length || 0;
  if (!count) return;
  const next = ((target % count) + count) % count;
  if (resetAutoplay) resetHeroAutoplay();
  if (next === heroIndex) return;

  const outgoing = slides.children[heroIndex];
  const incoming = slides.children[next];
  const direction = requestedDirection || (next > heroIndex ? 1 : -1);
  clearTimeout(heroCleanupTimer);
  cancelAnimationFrame(heroFrame);
  slides.querySelectorAll('.is-leaving,.is-entering').forEach(slide => {
    slide.classList.remove('is-leaving', 'is-entering');
  });

  // Prepare the incoming picture off to the side, then animate it into view.
  incoming.style.setProperty('--hero-enter-x', direction > 0 ? '4%' : '-4%');
  outgoing.style.setProperty('--hero-exit-x', direction > 0 ? '-4%' : '4%');
  incoming.classList.remove('active');
  incoming.classList.add('is-entering');
  incoming.setAttribute('aria-hidden', 'true');
  outgoing.classList.remove('active');
  outgoing.classList.add('is-leaving');
  outgoing.setAttribute('aria-hidden', 'true');
  heroIndex = next;
  dots?.querySelectorAll('[data-hero-dot]').forEach((dot, i) => {
    dot.classList.toggle('active', i === next);
    dot.setAttribute('aria-current', i === next ? 'true' : 'false');
  });

  // Force the browser to register the starting position so the CSS transition runs.
  void incoming.offsetWidth;
  heroFrame = requestAnimationFrame(() => {
    if (slides.children[next] !== incoming || heroIndex !== next) return;
    incoming.classList.remove('is-entering');
    incoming.classList.add('active');
    incoming.setAttribute('aria-hidden', 'false');
  });
  heroCleanupTimer = setTimeout(() => outgoing.classList.remove('is-leaving'), HERO_TRANSITION_MS);
}

