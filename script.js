function updateClock() {
  const now = new Date();
  const locale = currentLang === 'ar' ? 'ar-PS' : 'en-GB';
  localTimeEl.textContent = new Intl.DateTimeFormat(locale, { hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: false }).format(now);
  dateEl.textContent = new Intl.DateTimeFormat(locale, { weekday: 'long', day: 'numeric', month: 'long' }).format(now);
  const tz = Intl.DateTimeFormat().resolvedOptions().timeZone;
  if (tz) localTimeEl.title = tz;
}

function weatherDescription(code) {
  if (code === 0) return ['weatherClear', '☀️'];
  if (code === 1) return ['weatherMostlyClear', '🌤️'];
  if (code === 2) return ['weatherPartlyCloudy', '⛅'];
  if (code === 3) return ['weatherCloudy', '☁️'];
  if ([45, 48].includes(code)) return ['weatherFog', '🌫️'];
  if ([51, 53, 55, 56, 57].includes(code)) return ['weatherDrizzle', '🌦️'];
  if ([61, 63, 65, 66, 67].includes(code)) return ['weatherRain', '🌧️'];
  if ([71, 73, 75, 77].includes(code)) return ['weatherSnow', '🌨️'];
  if ([80, 81, 82].includes(code)) return ['weatherShowers', '🌦️'];
  if ([85, 86].includes(code)) return ['weatherSnowShowers', '🌨️'];
  if ([95, 96, 99].includes(code)) return ['weatherThunder', '⛈️'];
  return ['weatherUnknown', '🌡️'];
}

function renderWeather() {
  weatherBox.classList.toggle('loading', weatherState.status === 'loading');
  weatherBox.classList.toggle('error', weatherState.status === 'error');

  if (weatherState.status === 'loading') {
    weatherIcon.textContent = '◌';
    weatherLocation.textContent = t('weatherLoadingTitle');
    weatherDetails.textContent = t('weatherLoadingHint');
    return;
  }

  if (weatherState.status === 'error') {
    weatherIcon.textContent = '⌖';
    weatherLocation.textContent = t('weatherUnavailableTitle');
    weatherDetails.textContent = weatherState.permissionDenied ? t('weatherDeniedHint') : t('weatherUnavailableHint');
    return;
  }

  if (weatherState.weather) {
    const current = weatherState.weather.current;
    const [descKey, icon] = weatherDescription(current.weather_code);
    const locationName = buildPlaceLabel(weatherState.place) || t('weatherCurrentLocation');
    weatherIcon.textContent = current.is_day === 0 && current.weather_code <= 1 ? '🌙' : icon;
    weatherLocation.textContent = locationName;
    const temp = Math.round(current.temperature_2m);
    const feels = Math.round(current.apparent_temperature);
    weatherDetails.textContent = `${temp}°C • ${t(descKey)} • ${t('weatherFeels')} ${feels}°`;
    return;
  }

  weatherIcon.textContent = '⌖';
  weatherLocation.textContent = t('weatherRequestTitle');
  weatherDetails.textContent = t('weatherRequestHint');
}

function buildPlaceLabel(place) {
  if (!place) return '';
  const city = place.city || place.locality || place.principalSubdivision || '';
  const country = place.countryName || '';
  if (city && country && city.toLowerCase() !== country.toLowerCase()) {
    return currentLang === 'ar' ? `${city}، ${country}` : `${city}, ${country}`;
  }
  return city || country;
}

async function fetchWeather(latitude, longitude) {
  const params = new URLSearchParams({
    latitude: latitude.toFixed(5),
    longitude: longitude.toFixed(5),
    current: 'temperature_2m,apparent_temperature,weather_code,wind_speed_10m,is_day',
    timezone: 'auto'
  });
  const response = await fetch(`https://api.open-meteo.com/v1/forecast?${params.toString()}`);
  if (!response.ok) throw new Error('weather');
  return response.json();
}

async function fetchPlace(latitude, longitude) {
  const params = new URLSearchParams({
    latitude: latitude.toFixed(6),
    longitude: longitude.toFixed(6),
    localityLanguage: currentLang === 'ar' ? 'ar' : 'en'
  });
  const response = await fetch(`https://api.bigdatacloud.net/data/reverse-geocode-client?${params.toString()}`);
  if (!response.ok) throw new Error('place');
  return response.json();
}

async function refreshPlaceName() {
  if (!weatherState.coords) return;
  try {
    weatherState.place = await fetchPlace(weatherState.coords.latitude, weatherState.coords.longitude);
    renderWeather();
  } catch (_) {
    renderWeather();
  }
}

function requestLocalWeather() {
  if (!('geolocation' in navigator)) {
    weatherState.status = 'error';
    weatherState.permissionDenied = false;
    renderWeather();
    weatherDetails.textContent = t('weatherNotSupported');
    return;
  }

  weatherState.status = 'loading';
  weatherState.permissionDenied = false;
  renderWeather();

  navigator.geolocation.getCurrentPosition(async position => {
    const coords = { latitude: position.coords.latitude, longitude: position.coords.longitude };
    weatherState.coords = coords;
    try {
      const [weatherResult, placeResult] = await Promise.allSettled([
        fetchWeather(coords.latitude, coords.longitude),
        fetchPlace(coords.latitude, coords.longitude)
      ]);
      if (weatherResult.status !== 'fulfilled') throw new Error('weather');
      weatherState.weather = weatherResult.value;
      weatherState.place = placeResult.status === 'fulfilled' ? placeResult.value : null;
      weatherState.status = 'ready';
      renderWeather();
    } catch (_) {
      weatherState.status = 'error';
      renderWeather();
    }
  }, error => {
    weatherState.status = 'error';
    weatherState.permissionDenied = error.code === 1;
    renderWeather();
  }, {
    enableHighAccuracy: false,
    timeout: 12000,
    maximumAge: 10 * 60 * 1000
  });
}

