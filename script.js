function scheduleGalleryJob(article, job) {
  if (galleryBusy) {
    // A thumbnail click supersedes queued arrow presses; otherwise each press
    // is played in sequence instead of producing a broken, abrupt jump.
    if (job.kind === 'index') galleryQueue = [job];
    else if (galleryQueue.length < 8) galleryQueue.push(job);
    return;
  }
  const images = galleryImageList(article);
  if (images.length < 2 || String(openedArticleId) !== String(article.id)) return;
  const rawIndex = job.kind === 'step' ? activeGalleryIndex + job.step : job.index;
  const nextIndex = ((rawIndex % images.length) + images.length) % images.length;
  if (nextIndex === activeGalleryIndex) return;
  const direction = job.kind === 'step' ? Math.sign(job.step)
    : (job.direction || (nextIndex > activeGalleryIndex ? 1 : -1));
  animateGallery(article, nextIndex, direction);
}
